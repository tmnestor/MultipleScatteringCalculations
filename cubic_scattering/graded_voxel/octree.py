@dataclass
class OctreeResult:
    """Solution of the Galerkin system on the leaves of an octree, for one plane wave."""

    centres: NDArray  # (N, 3)
    half_widths: NDArray  # (N,)
    omega: float
    ref: ReferenceMedium
    delta: NDArray | list[NDArray]  # per leaf (4 or 10, 9, 9): contrast operator coefficients
    psi: NDArray | list[NDArray]  # per leaf (4 or 10, 9): coefficients of the state
    # arrays when every leaf has the same degrees, lists of per-leaf arrays otherwise
    p: int
    r: int


@dataclass
class _OctreeSystem:
    """The assembled Galerkin system (M - K E) psi = b of a tree, with its per-leaf bookkeeping."""

    a: NDArray  # the dense matrix M - K E
    rhs: NDArray  # the moments b of the incident state
    start: NDArray  # first row of each leaf
    sizes: list  # field_sizes of each leaf
    delta: list  # contrast coefficients of each leaf
    gram: list  # Gram matrix of each leaf's field functions (na x na)
    p_leaf: NDArray
    r_leaf: NDArray


def _assemble_octree(
    omega: float,
    ref: ReferenceMedium,
    contrast: MaterialContrast,
    centres: NDArray,
    half_widths: NDArray,
    profile: Callable[[NDArray], float],
    k_hat: NDArray,
    pol: NDArray,
    wave_type: str,
    p: int | NDArray,
    r: int | NDArray,
    block_cache: dict | None,
) -> _OctreeSystem:
    """Assemble the system of ``solve_graded_octree``; arguments and errors as there."""
    centres = np.asarray(centres, dtype=float)
    half_widths = np.asarray(half_widths, dtype=float)
    n = len(centres)
    p_leaf = np.broadcast_to(np.asarray(p, dtype=int), (n,))
    r_leaf = np.broadcast_to(np.asarray(r, dtype=int), (n,))
    store: dict = block_cache if block_cache is not None else {}
    medium = (float(omega), float(ref.alpha), float(ref.beta), float(ref.rho))
    if store.setdefault("medium", medium) != medium:
        raise ValueError(
            f"solve_graded_octree: block_cache holds blocks for (omega, alpha, beta, rho) = "
            f"{store['medium']}, but this solve has {medium}. Coupling blocks depend on the frequency "
            "and the background. Fix: pass a separate dictionary for each frequency and background, "
            "e.g. block_cache=caches.setdefault(omega, {})."
        )
    sizes = [field_sizes(int(pi), int(ri)) for pi, ri in zip(p_leaf, r_leaf, strict=True)]
    delta = [
        cell_contrast_coefficients(profile, c, float(h), contrast, ref, omega, degree=int(ri))
        for c, h, ri in zip(centres, half_widths, r_leaf, strict=True)
    ]
    rows = np.array([sz[0] * 9 for sz in sizes])
    start = np.concatenate([[0], np.cumsum(rows)])
    a = np.zeros((start[-1], start[-1]), dtype=complex)
    h_min = float(half_widths.min())
    cache_k: dict[tuple, NDArray] = {}
    expansions = [
        source_expansion(d, sz[1])[:, : sz[0]].transpose(0, 2, 1, 3).reshape(sz[3] * 9, sz[0] * 9)
        for d, sz in zip(delta, sizes, strict=True)
    ]
    for col in range(n):
        n_source = sizes[col][3]
        for row in range(n):
            na, n_field = sizes[row][0], sizes[row][1]
            rel = np.round((centres[row] - centres[col]) / h_min).astype(int)
            key = (
                float(half_widths[row]),
                float(half_widths[col]),
                int(rel[0]),
                int(rel[1]),
                int(rel[2]),
                na,
                n_field,
                n_source,
            )
            if key not in cache_k:
                tree_key = ("tree", n_source, n_field, h_min)
                if tree_key not in store:
                    equal = store.setdefault(
                        ("equal", n_source, n_field), EqualBlocks(omega, ref, n_source, n_field)
                    )
                    store[tree_key] = TreeBlocks(omega, ref, h_min, n_source, n_field, equal)
                blk = store[tree_key]((int(rel[0]), int(rel[1]), int(rel[2])), key[0], key[1])
                cache_k[key] = blk[:na].transpose(0, 2, 1, 3).reshape(na * 9, n_source * 9)
            entry = -(cache_k[key] @ expansions[col])
            if row == col:
                entry = entry + np.kron(gram_test(float(half_widths[row]), n_field)[:na, :na], np.eye(9))
            a[start[row] : start[row + 1], start[col] : start[col + 1]] = entry
    k_mag = omega / (ref.alpha if wave_type == "P" else ref.beta)
    k_hat = np.asarray(k_hat, dtype=float) / np.linalg.norm(k_hat)
    amp = np.concatenate([np.asarray(pol, dtype=complex), _plane_wave_strain_voigt(k_hat, pol, k_mag)])
    rhs = np.zeros(start[-1], dtype=complex)
    for i, (c, h, sz) in enumerate(zip(centres, half_widths, sizes, strict=True)):
        mom = plane_wave_moments(c[None, :], float(h), k_mag * k_hat, amp, sz[1])[0, : sz[0]]
        rhs[start[i] : start[i + 1]] = mom.ravel()
    gram = [gram_test(float(h), sz[1])[: sz[0], : sz[0]] for h, sz in zip(half_widths, sizes, strict=True)]
    return _OctreeSystem(a, rhs, start, sizes, delta, gram, p_leaf, r_leaf)


def _octree_result(
    system: _OctreeSystem,
    coeffs: NDArray,
    centres: NDArray,
    half_widths: NDArray,
    omega: float,
    ref: ReferenceMedium,
) -> OctreeResult:
    """Package a vector of leaf coefficients as an OctreeResult."""
    psi = []
    for i, sz in enumerate(system.sizes):
        full = np.zeros((sz[1], 9), dtype=complex)
        full[: sz[0]] = coeffs[system.start[i] : system.start[i + 1]].reshape(sz[0], 9)
        psi.append(full)
    delta = system.delta
    same = len({(f.shape, d.shape) for f, d in zip(psi, delta, strict=True)}) == 1
    return OctreeResult(
        np.asarray(centres, dtype=float),
        np.asarray(half_widths, dtype=float),
        omega,
        ref,
        np.array(delta) if same else delta,
        np.array(psi) if same else psi,
        int(system.p_leaf.max()),
        int(system.r_leaf.max()),
    )


def solve_graded_octree(
    omega: float,
    ref: ReferenceMedium,
    contrast: MaterialContrast,
    centres: NDArray,
    half_widths: NDArray,
    profile: Callable[[NDArray], float],
    k_hat: NDArray,
    pol: NDArray,
    wave_type: str,
    p: int | NDArray = 1,
    r: int | NDArray = 1,
    block_cache: dict | None = None,
) -> OctreeResult:
    """Solve the Galerkin system on leaves of mixed sizes, densely.

    The field degree and the contrast degree may differ from leaf to leaf: a large leaf in a uniform part
    of the medium needs no more than a constant contrast, but it needs a richer basis for the wavefield
    than a small leaf does.

    Args:
        omega: Angular frequency (rad/s).
        ref: Background medium.
        contrast: The contrast that ``profile`` scales.
        centres: Leaf centres, shape (N, 3) (m).
        half_widths: Leaf half-widths, shape (N,) (m), in ratios 2^j.
        profile: Scalar factor of the contrast as a function of position.
        k_hat: Incident direction.
        pol: Incident polarisation.
        wave_type: 'P' or 'S' (the incident speed).
        p: Field degree (0, 1 or 2): one value, or one per leaf.
        r: Contrast degree (0, 1 or 2): one value, or one per leaf.
        block_cache: A dictionary that carries the coupling blocks from one solve to the next (other
            trees, other contrasts, other incident waves).  The blocks depend on the frequency and the
            background only, and the dictionary remembers both.

    Raises:
        ValueError: when block_cache was filled at another frequency or background.
    """
    system = _assemble_octree(
        omega, ref, contrast, centres, half_widths, profile, k_hat, pol, wave_type, p, r, block_cache
    )
    sol = scipy.linalg.solve(system.a, system.rhs, overwrite_a=True, check_finite=False)
    return _octree_result(system, sol, centres, half_widths, omega, ref)


def born_series_octree(
    omega: float,
    ref: ReferenceMedium,
    contrast: MaterialContrast,
    centres: NDArray,
    half_widths: NDArray,
    profile: Callable[[NDArray], float],
    k_hat: NDArray,
    pol: NDArray,
    wave_type: str,
    orders: int,
    p: int | NDArray = 1,
    r: int | NDArray = 1,
    block_cache: dict | None = None,
) -> list[OctreeResult]:
    """The scheme's Born series on a tree, term by term, with no solve.

    The system (M - K E) psi = b gives psi = sum_n psi_n with psi_1 = M^-1 b and
    psi_{n+1} = M^-1 (K E) psi_n, where K E psi = M psi - (M - K E) psi. Term n is the part of the
    scheme's response of order n in the contrast: its far field (``octree_far_field``) is the scheme's
    T_n. Each further term costs one product with the assembled matrix. Arguments as
    ``solve_graded_octree``; ``orders`` is the number of terms returned (psi_1 .. psi_orders).

    Raises:
        ValueError: when orders < 1, or as ``solve_graded_octree``.
    """
    if orders < 1:
        raise ValueError(
            f"born_series_octree: orders = {orders}; at least one term is needed.\n"
            "  Fix: pass orders >= 1 (orders = 2 gives the Born term and the term of second order)."
        )
    system = _assemble_octree(
        omega, ref, contrast, centres, half_widths, profile, k_hat, pol, wave_type, p, r, block_cache
    )

    def m_apply(vec: NDArray, inverse: bool) -> NDArray:
        out = np.empty_like(vec)
        for i, g in enumerate(system.gram):
            blk = vec[system.start[i] : system.start[i + 1]].reshape(g.shape[0], 9)
            out[system.start[i] : system.start[i + 1]] = (
                np.linalg.solve(g, blk) if inverse else g @ blk
            ).ravel()
        return out

    terms = [m_apply(system.rhs, inverse=True)]
    for _ in range(orders - 1):
        prev = terms[-1]
        terms.append(m_apply(m_apply(prev, inverse=False) - system.a @ prev, inverse=True))
    return [_octree_result(system, t, centres, half_widths, omega, ref) for t in terms]


def born_octree(
    omega: float,
    ref: ReferenceMedium,
    contrast: MaterialContrast,
    centres: NDArray,
    half_widths: NDArray,
    profile: Callable[[NDArray], float],
    k_hat: NDArray,
    pol: NDArray,
    wave_type: str,
    p: int | NDArray = 1,
    r: int | NDArray = 1,
) -> OctreeResult:
    """The term of first order in the contrast, with no solve: each leaf holds the projected incident wave.

    The Galerkin system at first order is M psi = <Q, psi0>, so psi is the L2 projection of the incident
    state onto the leaf's field functions.  Its far field (octree_far_field) is the scheme's Born term,
    which costs one pass over the leaves; against the Born term of a finer representation it gives the
    first-order part of the scheme's error before anything is solved.  Arguments as solve_graded_octree.
    """
    centres = np.asarray(centres, dtype=float)
    half_widths = np.asarray(half_widths, dtype=float)
    n = len(centres)
    p_leaf = np.broadcast_to(np.asarray(p, dtype=int), (n,))
    r_leaf = np.broadcast_to(np.asarray(r, dtype=int), (n,))
    k_mag = omega / (ref.alpha if wave_type == "P" else ref.beta)
    k_hat = np.asarray(k_hat, dtype=float) / np.linalg.norm(k_hat)
    amp = np.concatenate([np.asarray(pol, dtype=complex), _plane_wave_strain_voigt(k_hat, pol, k_mag)])
    delta, psi = [], []
    for c, h, pi, ri in zip(centres, half_widths, p_leaf, r_leaf, strict=True):
        na, n_field, _, _ = field_sizes(int(pi), int(ri))
        delta.append(cell_contrast_coefficients(profile, c, float(h), contrast, ref, omega, degree=int(ri)))
        mom = plane_wave_moments(c[None, :], float(h), k_mag * k_hat, amp, n_field)[0, :na]
        full = np.zeros((n_field, 9), dtype=complex)
        full[:na] = np.linalg.solve(gram_test(float(h), n_field)[:na, :na], mom)
        psi.append(full)
    same = len({(f.shape, d.shape) for f, d in zip(psi, delta, strict=True)}) == 1
    return OctreeResult(
        centres,
        half_widths,
        omega,
        ref,
        np.array(delta) if same else delta,
        np.array(psi) if same else psi,
        int(p_leaf.max()),
        int(r_leaf.max()),
    )


def octree_far_field(
    res: OctreeResult, directions: NDArray, r_distance: float, n_gauss: int = 4
) -> tuple[NDArray, NDArray]:
    """Far field (u_P, u_S) of the leaves: each leaf's polynomial source radiated from Gauss nodes."""
    x, w = leggauss(n_gauss)
    xi = np.stack(np.meshgrid(x, x, x, indexing="ij"), -1).reshape(-1, 3)
    ww = np.einsum("i,j,k->ijk", w, w, w).ravel()
    ms = monomials(SOURCE_EXPONENTS_QUARTIC, xi)
    pts, srcs = [], []
    for c, h, d, psi in zip(res.centres, res.half_widths, res.delta, res.psi, strict=True):
        coef = np.einsum("cbij,bj->ci", source_expansion(d, psi.shape[0]), psi)
        srcs.append((ms[: len(coef)].T @ coef) * (ww * h**3)[:, None])
        pts.append(c + h * xi)
    return radiate(np.concatenate(pts), np.concatenate(srcs), res.omega, res.ref, directions, r_distance)


# ---------------------------------------------------------------------------
# Refinement by the detail coefficients of the medium
# ---------------------------------------------------------------------------

N_FUN = {0: 1, 1: 4, 2: 10}


def leaf_energies(
    profile: Callable[[NDArray], NDArray], centres: NDArray, half_widths: NDArray, p: int, levels: int = 3
) -> tuple[NDArray, NDArray, NDArray]:
    """Per leaf: (defect, detail, norm) of a scalar profile against the leaf's polynomials of degree p.

    defect = int (s - P s)^2 over the leaf, P the L2 projection onto the leaf's polynomials, obtained as
    int s^2 - |P s|^2 (orthogonality), with int s^2 from a Gauss rule on the descendants ``levels`` deep;
    detail = |P_children s|^2 - |P s|^2, the energy of the leaf's own detail coefficients, which is what
    one refinement of the leaf recovers; norm = int s^2 (on the fine descendants).

    Args:
        profile: Vectorised: positions (..., 3) to values (...).
        centres: Leaf centres (N, 3).
        half_widths: Leaf half-widths (N,).
        p: Polynomial degree of the cells (0, 1 or 2).
        levels: Depth of the descendants that stand for the exact profile.
    """
    x, w = leggauss(6)
    xi = np.stack([g.ravel() for g in np.meshgrid(x, x, x, indexing="ij")], axis=1)
    wt = (w[:, None, None] * w[None, :, None] * w[None, None, :]).ravel()
    basis = contrast_values(xi)[: N_FUN[p]]
    norms = np.array(CONTRAST_NORMS[: N_FUN[p]])

    def energy(c: NDArray, h: float, depth: int) -> tuple[float, float]:
        kids, hk = _descendants(c, h, depth)
        vals = profile(kids[:, None, :] + hk * xi[None, :, :])
        coef = (vals * wt) @ basis.T / norms
        return float((coef**2 * norms).sum() * hk**3), float(((vals**2) @ wt).sum() * hk**3)

    n = len(centres)
    defect, detail, norm = np.zeros(n), np.zeros(n), np.zeros(n)
    for i, (c, h) in enumerate(zip(centres, half_widths, strict=True)):
        e0, _ = energy(c, float(h), 0)
        e1, _ = energy(c, float(h), 1)
        _, nf = energy(c, float(h), levels)
        defect[i], detail[i], norm[i] = max(nf - e0, 0.0), max(e1 - e0, 0.0), nf
    return defect, detail, norm


def adapt_leaves(
    profile: Callable[[NDArray], NDArray],
    centres: NDArray,
    half_widths: NDArray,
    p: int,
    tol: float,
    h_min: float,
) -> tuple[NDArray, NDArray]:
    """Refine, repeatedly, every leaf whose own detail energy exceeds ``tol`` times the total energy of
    the profile, down to half-width ``h_min``; then drop the leaves on which the profile vanishes.

    The detail energy of a leaf is the part of the projection defect that one refinement of that leaf
    removes, so the rule spends cells where the defect is.
    """
    centres, half_widths = np.asarray(centres, dtype=float), np.asarray(half_widths, dtype=float)
    while True:
        _, detail, norm = leaf_energies(profile, centres, half_widths, p, levels=2)
        flag = (detail > tol * norm.sum()) & (half_widths > h_min * (1.0 + 1e-9))
        if not flag.any():
            keep = norm > 0.0
            return centres[keep], half_widths[keep]
        centres, half_widths = refine_leaves(centres, half_widths, flag)


