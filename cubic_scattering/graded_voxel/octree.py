Triple = tuple[float, float, float]


@cache
def field_reexpansion(n_field: int, scale: float, shift: Triple) -> NDArray:
    """C[a, b] with Q_a(scale * xi + shift) = sum_b C[a, b] Q_b(xi), shape (n_field, n_field).

    By projection onto the orthogonal Q_b with a Gauss rule that is exact for the products.
    """
    x, w = np.polynomial.legendre.leggauss(4)
    xi = np.stack([g.ravel() for g in np.meshgrid(x, x, x, indexing="ij")], axis=1)
    wt = (w[:, None, None] * w[None, :, None] * w[None, None, :]).ravel()
    child = contrast_values(xi)[:n_field]
    parent = contrast_values(scale * xi + np.asarray(shift))[:n_field]
    return (parent * wt) @ child.T / np.array(CONTRAST_NORMS[:n_field])


@cache
def source_reexpansion(n_source: int, scale: float, shift: Triple) -> NDArray:
    """D[c, d] with m_c(scale * xi + shift) = sum_d D[c, d] m_d(xi), shape (n_source, n_source).

    Exactly, by the binomial expansion of (scale * xi_i + shift_i)^e on each axis.
    """
    exps = source_exponents(n_source)
    index = {e: k for k, e in enumerate(exps)}
    out = np.zeros((n_source, n_source))
    for c, e in enumerate(exps):
        axes = [
            [math.comb(e[i], j) * scale**j * shift[i] ** (e[i] - j) for j in range(e[i] + 1)]
            for i in range(3)
        ]
        for j0, j1, j2 in itertools.product(*(range(len(a)) for a in axes)):
            out[c, index[(j0, j1, j2)]] += axes[0][j0] * axes[1][j1] * axes[2][j2]
    return out


class EqualBlocks:
    """Equal-cell blocks K(offset; h) for one frequency and medium, each orbit of the cube group computed
    once (``blocks.coupling_block``) and the rest generated by symmetry (``fft._transform``)."""

    def __init__(self, omega: float, ref: ReferenceMedium, n_source: int = 10, n_test: int = 4) -> None:
        self.omega, self.ref, self.n_source, self.n_test = omega, ref, n_source, n_test
        self._canonical: dict[tuple[float, tuple[int, int, int]], NDArray] = {}
        self._blocks: dict[tuple[float, tuple[int, int, int]], NDArray] = {}

    def __call__(self, offset: tuple[int, int, int], h: float) -> NDArray:
        key = (h, offset)
        if key not in self._blocks:
            a, b, d = sorted((abs(o) for o in offset), reverse=True)
            canon = (a, b, d)
            if (h, canon) not in self._canonical:
                self._canonical[(h, canon)] = coupling_block(
                    canon, h, self.omega, self.ref, self.n_source, self.n_test
                )
            cv, target = np.array(canon, dtype=float), np.array(offset, dtype=float)
            q = next(q for q in signed_permutations() if np.array_equal(q @ cv, target))
            self._blocks[key] = _transform(q, self._canonical[(h, canon)])
        return self._blocks[key]


def _levels_apart(h_large: float, h_small: float) -> int:
    ratio = h_large / h_small
    j = round(math.log2(ratio))
    if j < 0 or abs(2.0**j - ratio) > 1e-9 * ratio:
        raise ValueError(
            f"octree_block: the cell sizes {h_large} and {h_small} are not in a ratio that is a power "
            f"of two "
            f"(ratio {ratio:.6g}). Fix: use cells of an octree, half-widths H / 2^j."
        )
    return j


def _descendants(centre: NDArray, h_large: float, j: int) -> tuple[NDArray, float]:
    """Centres of the 8^j descendants of half-width h_large / 2^j, shape (8^j, 3), and that half-width."""
    m = 2**j
    h = h_large / m
    steps = (2 * np.arange(m) + 1 - m) * h
    grid = np.stack([g.ravel() for g in np.meshgrid(steps, steps, steps, indexing="ij")], axis=1)
    return centre + grid, h


def _offset(c_field: NDArray, c_source: NDArray, h: float) -> tuple[int, int, int]:
    off = (c_field - c_source) / (2.0 * h)
    nearest = np.round(off)
    if np.abs(off - nearest).max() > 1e-9:
        raise ValueError(
            f"octree_block: the cells are not aligned as octree cells: the separation {c_field - c_source} "
            f"is not a whole number of cell widths {2.0 * h}. Fix: place cell centres on the lattice "
            "of the octree."
        )
    return (int(nearest[0]), int(nearest[1]), int(nearest[2]))


def octree_block(
    c_field: Triple,
    h_field: float,
    c_source: Triple,
    h_source: float,
    omega: float,
    ref: ReferenceMedium,
    n_source: int = 10,
    n_test: int = 4,
    equal: EqualBlocks | None = None,
) -> NDArray:
    """K[a, c] between two octree cells of any two sizes, shape (n_test, n_source, 9, 9).

    Args:
        c_field: Centre of the field cell (m).
        h_field: Its half-width (m).
        c_source: Centre of the source cell (m).
        h_source: Its half-width (m).
        omega: Angular frequency (rad/s).
        ref: Background medium.
        n_source: Source monomials (10, 20 or 35).
        n_test: Field functions (4 or 10).
        equal: A cache of equal-cell blocks to draw on (None: each is computed afresh).

    Raises:
        ValueError: when the sizes are not in a ratio 2^j or the cells are not on a common lattice.
    """
    ct, cs = np.asarray(c_field, dtype=float), np.asarray(c_source, dtype=float)

    def eq(offset: tuple[int, int, int], h: float) -> NDArray:
        if equal is not None:
            return equal(offset, h)
        return coupling_block(offset, h, omega, ref, n_source, n_test)

    if h_field >= h_source:
        j = _levels_apart(h_field, h_source)
        if j == 0:
            return eq(_offset(ct, cs, h_source), h_source)
        kids, h = _descendants(ct, h_field, j)
        shifts = (kids - ct) / h_field
        c_mats = np.array([field_reexpansion(n_test, h / h_field, tuple(map(float, s))) for s in shifts])
        blocks = np.array([eq(_offset(kid, cs, h), h) for kid in kids])
        return np.einsum("kab,kbcij->acij", c_mats, blocks)
    j = _levels_apart(h_source, h_field)
    kids, h = _descendants(cs, h_source, j)
    shifts = (kids - cs) / h_source
    d_mats = np.array([source_reexpansion(n_source, h / h_source, tuple(map(float, s))) for s in shifts])
    blocks = np.array([eq(_offset(ct, kid, h), h) for kid in kids])
    return np.einsum("kaeij,kce->acij", blocks, d_mats)


class TreeBlocks:
    """Blocks between octree cells of any two sizes, one computed per orbit of the cube group.

    Two pairs of cells whose relative positions are images of one another under a signed permutation of
    the axes have blocks related by the representations of that permutation (fft._transform), whatever
    the two sizes: the group acts on both cells alike.  Of the pairs of leaves of a tree, almost all are
    such images, so the descent to the smaller size (octree_block) is made once for each orbit.

    Args:
        omega: Angular frequency (rad/s).
        ref: Background medium.
        unit: The length in which relative positions are given (m): the smallest half-width of the tree.
        n_source: Source monomials (10, 20 or 35).
        n_test: Field functions (4 or 10).
        equal: Equal-cell blocks to draw on, for the same frequency, medium and sizes (None: its own).
    """

    def __init__(
        self,
        omega: float,
        ref: ReferenceMedium,
        unit: float,
        n_source: int = 10,
        n_test: int = 4,
        equal: EqualBlocks | None = None,
    ) -> None:
        self.omega, self.ref, self.unit, self.n_source, self.n_test = omega, ref, unit, n_source, n_test
        self.equal = equal if equal is not None else EqualBlocks(omega, ref, n_source, n_test)
        self._canonical: dict[tuple, NDArray] = {}
        self.computed = 0  # canonical blocks between unequal cells computed so far

    def __call__(self, rel: tuple[int, int, int], h_field: float, h_source: float) -> NDArray:
        """K[a, c] for a field cell at rel x unit from the source cell, shape (n_test, n_source, 9, 9)."""
        a, b, d = sorted((abs(o) for o in rel), reverse=True)
        canon = (a, b, d)
        key = (h_field, h_source, canon)
        if key not in self._canonical:
            self._canonical[key] = octree_block(
                (0.0, 0.0, 0.0),
                h_field,
                (-canon[0] * self.unit, -canon[1] * self.unit, -canon[2] * self.unit),
                h_source,
                self.omega,
                self.ref,
                self.n_source,
                self.n_test,
                self.equal,
            )
            self.computed += h_field != h_source
        if tuple(rel) == canon:
            return self._canonical[key]
        cv, target = np.array(canon, dtype=float), np.array(rel, dtype=float)
        q = next(q for q in signed_permutations() if np.array_equal(q @ cv, target))
        return _transform(q, self._canonical[key])


